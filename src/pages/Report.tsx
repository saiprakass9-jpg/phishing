import React from 'react';
import { useLocation, useNavigate } from 'react-router-dom';
import { Shield, ArrowLeft, Download } from 'lucide-react';
import { Button } from '@/components/ui/button';
import { useLanguage } from '@/context/LanguageContext';

export default function Report() {
  const location = useLocation();
  const navigate = useNavigate();
  const { t } = useLanguage();
  const result = location.state?.result;

  if (!result) {
    // If accessed directly without state, redirect to home
    React.useEffect(() => {
      navigate('/');
    }, [navigate]);
    return null;
  }

  const averageConfidence = result.aggregate?.score ?? (result.svm.confidence + result.lightgbm.confidence) / 2;
  const isBlacklisted = result.isBlacklisted;
  const isPhishing = result.svm.isPhishing || result.lightgbm.isPhishing || isBlacklisted;
  const isSuspicious = !isPhishing && (result.svm.isSuspicious || result.lightgbm.isSuspicious);

  let statusText = t('report.status.safe');
  let statusColor = 'text-emerald-600';
  let statusDescription = t('report.status.safe.desc');

  if (isBlacklisted) {
    statusText = t('report.status.blocked');
    statusColor = 'text-red-700';
    statusDescription = t('report.status.blocked.desc');
  } else if (isPhishing) {
    statusText = t('report.status.phishing');
    statusColor = 'text-red-600';
    statusDescription = t('report.status.phishing.desc');
  } else if (isSuspicious) {
    statusText = t('report.status.suspicious');
    statusColor = 'text-amber-600';
    statusDescription = t('report.status.suspicious.desc');
  }

  const handleDownloadReport = () => {
    const reportText = `PHISHGUARD AI - SECURITY ANALYSIS REPORT
========================================
Date: ${new Date().toLocaleString()}
Target URL: ${result.url}

EXECUTIVE SUMMARY
-----------------
The analyzed URL has been classified as ${statusText} with an aggregate confidence score of ${averageConfidence.toFixed(1)}%.
${statusDescription}

MODEL PREDICTIONS
-----------------
- Support Vector Machine (SVM): ${result.svm.label} (${result.svm.confidence.toFixed(1)}% confidence)
- LightGBM: ${result.lightgbm.label} (${result.lightgbm.confidence.toFixed(1)}% confidence)

AI ANALYSIS REPORT
------------------
${result.explanation || 'No detailed AI explanation available.'}

TECHNICAL FEATURE ANALYSIS
--------------------------
- URL Length: ${result.features.urlLength} characters
- IP Address Presence: ${result.features.hasIpAddress ? 'Yes (Suspicious)' : 'No (Normal)'}
- '@' Symbol: ${result.features.hasAtSymbol ? 'Yes (Suspicious)' : 'No (Normal)'}
- Redirect '//' Symbol: ${result.features.hasDoubleSlash ? 'Yes (Suspicious)' : 'No (Normal)'}
- HTTPS Protocol: ${result.features.hasHttps ? 'Yes (Secure)' : 'No (Insecure)'}
- Subdomain Count: ${result.features.subdomainCount}
- Suspicious Keywords: ${result.features.hasSuspiciousWords ? 'Detected (Suspicious)' : 'None Detected'}

========================================
Generated by PhishGuard AI`;

    const blob = new Blob([reportText], { type: 'text/plain' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `PhishGuard_Report_${new Date().getTime()}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
  };

  return (
    <div className="min-h-screen bg-slate-50 text-slate-900 font-sans flex flex-col">
      <header className="bg-white border-b border-slate-200 sticky top-0 z-10">
        <div className="max-w-5xl mx-auto px-4 sm:px-6 lg:px-8 h-16 flex items-center justify-between">
          <div className="flex items-center gap-2 cursor-pointer" onClick={() => navigate('/')}>
            <Shield className="h-8 w-8 text-indigo-600" />
            <span className="text-xl font-bold bg-clip-text text-transparent bg-gradient-to-r from-indigo-600 to-violet-600">
              {t('app.name')}
            </span>
          </div>
          <div className="flex items-center gap-4">
            <Button variant="ghost" onClick={() => navigate(-1)} className="gap-2">
              <ArrowLeft className="h-4 w-4" /> {t('report.back')}
            </Button>
            <Button onClick={handleDownloadReport} className="bg-indigo-600 hover:bg-indigo-700 text-white">
              <Download className="h-4 w-4 mr-2" /> {t('report.download')}
            </Button>
          </div>
        </div>
      </header>

      <main className="flex-grow p-4 sm:p-8 flex justify-center">
        <div className="w-full max-w-4xl bg-white border border-slate-200 shadow-sm rounded-xl p-8 sm:p-12 font-serif text-slate-800 space-y-8">
          <div className="text-center border-b border-slate-200 pb-8 mb-8">
            <h1 className="text-3xl font-bold uppercase tracking-widest text-slate-900 mb-3">{t('report.title')}</h1>
            <p className="text-slate-500 font-sans">{t('report.generated')} {new Date().toLocaleDateString()} at {new Date().toLocaleTimeString()}</p>
          </div>

          <section className="space-y-4">
            <h2 className="text-xl font-bold text-slate-900 uppercase tracking-wider border-b border-slate-100 pb-2">{t('report.summary.title')}</h2>
            <p className="leading-relaxed text-lg">
              {t('report.summary.text1')} <br/>
              <strong className="font-mono text-base break-all bg-slate-100 px-2 py-1 rounded mt-2 inline-block">{result.url}</strong>
            </p>
            <p className="leading-relaxed text-lg">
              {t('report.summary.text2')} <strong className={statusColor}>{statusText}</strong> {t('analysis.score.desc')} <strong>{averageConfidence.toFixed(1)}%</strong>. 
              {' ' + statusDescription}
            </p>
          </section>

          <section className="space-y-4">
            <h2 className="text-xl font-bold text-slate-900 uppercase tracking-wider border-b border-slate-100 pb-2">{t('report.models.title')}</h2>
            <p className="leading-relaxed text-lg">
              {t('report.models.text')}
            </p>
            <ul className="list-disc pl-8 space-y-3 text-lg">
              <li>
                <strong>{t('analysis.model.svm')}:</strong> {result.svm.label} ({result.svm.confidence.toFixed(1)}%)
              </li>
              <li>
                <strong>{t('analysis.model.lgbm')}:</strong> {result.lightgbm.label} ({result.lightgbm.confidence.toFixed(1)}%)
              </li>
            </ul>
          </section>

          {result.explanation && (
            <section className="space-y-4">
              <h2 className="text-xl font-bold text-slate-900 uppercase tracking-wider border-b border-slate-100 pb-2">{t('report.ai.title')}</h2>
              <p className="leading-relaxed text-lg bg-slate-50 p-6 rounded-lg border border-slate-100 italic text-slate-700">
                "{result.explanation}"
              </p>
            </section>
          )}

          <section className="space-y-4">
            <h2 className="text-xl font-bold text-slate-900 uppercase tracking-wider border-b border-slate-100 pb-2">{t('report.tech.title')}</h2>
            <p className="leading-relaxed text-lg">
              {t('report.tech.text')}
            </p>
            <ul className="list-disc pl-8 space-y-3 text-lg">
              <li><strong>{t('feature.urlLength')}:</strong> {result.features.urlLength} {t('common.chars')}</li>
              <li><strong>{t('feature.ipAddress')}:</strong> {result.features.hasIpAddress ? t('common.yes') : t('common.no')}</li>
              <li><strong>{t('feature.atSymbol')}:</strong> {result.features.hasAtSymbol ? t('common.yes') : t('common.no')}</li>
              <li><strong>{t('feature.redirect')}:</strong> {result.features.hasDoubleSlash ? t('common.yes') : t('common.no')}</li>
              <li><strong>{t('feature.https')}:</strong> {result.features.hasHttps ? t('common.yes') : t('common.no')}</li>
              <li><strong>{t('feature.subdomains')}:</strong> {result.features.subdomainCount}</li>
              <li><strong>{t('feature.keywords')}:</strong> {result.features.hasSuspiciousWords ? t('common.detected') : t('common.none')}</li>
            </ul>
          </section>
          
          <div className="pt-12 text-center text-sm text-slate-500 font-sans">
            <p>{t('report.end')}</p>
            <p className="mt-1">{t('report.system')}</p>
          </div>
        </div>
      </main>
    </div>
  );
}
